using System;
using System.IO;
using System.Linq;
using System.Collections.Generic;
using UnityEngine;
using UnityEditor;
using CurtainCall.EscapeRoute;

public static class SuccessArtBuilder
{
    const string Art="Assets/Scenes/Levels/SuccessEndingArt";
    const string Prefabs="Assets/Resources/Prefabs/Endings";
    const string Shaders="Assets/Scripts/EscapeRoute/Shaders";
    static System.Random random;
    static float R(float a,float b)=>a+(b-a)*(float)random.NextDouble();
    static readonly List<Vector3> vertices=new();
    static readonly List<Vector2> uvs=new();
    static readonly List<int> indices=new();
    static Transform Node(string name,Transform parent){var t=new GameObject(name).transform;t.SetParent(parent,false);return t;}
    static void ResetMesh(){vertices.Clear();uvs.Clear();indices.Clear();}
    static void Quad(Vector3 a,Vector3 b,Vector3 c,Vector3 d,float v0=0,float v1=1)
    {
        int i=vertices.Count;vertices.AddRange(new[]{a,b,c,d});uvs.AddRange(new[]{new Vector2(0,v0),new Vector2(1,v0),new Vector2(1,v1),new Vector2(0,v1)});
        indices.AddRange(new[]{i,i+2,i+1,i,i+3,i+2});
    }
    static Mesh SaveMesh(string name)
    {
        string path=Art+"/"+name+".asset";
        var mesh=AssetDatabase.LoadAssetAtPath<Mesh>(path);bool fresh=mesh==null;
        if(fresh)mesh=new Mesh{name=name};else mesh.Clear();
        mesh.indexFormat=UnityEngine.Rendering.IndexFormat.UInt32;
        mesh.SetVertices(vertices);mesh.SetUVs(0,uvs);mesh.SetTriangles(indices,0);mesh.RecalculateNormals();mesh.RecalculateBounds();
        if(fresh)AssetDatabase.CreateAsset(mesh,path);else EditorUtility.SetDirty(mesh);return mesh;
    }
    static Transform MeshObject(string name,Transform parent,Mesh mesh,Material mat)
    {
        var t=Node(name,parent);t.gameObject.AddComponent<MeshFilter>().sharedMesh=mesh;
        t.gameObject.AddComponent<MeshRenderer>().sharedMaterial=mat;return t;
    }
    static Material Mat(string name,Color color,int kind)
    {
        string path=Art+"/"+name+".mat";var m=AssetDatabase.LoadAssetAtPath<Material>(path);
        if(m==null){m=new Material(Shader.Find("CurtainCall/Endings/Success Landscape"));AssetDatabase.CreateAsset(m,path);}
        m.SetColor("_BaseColor",color);m.SetFloat("_Kind",kind);m.SetFloat("_DetailScale",kind==1?8:.7f);EditorUtility.SetDirty(m);return m;
    }
    static Transform Shape(string name,PrimitiveType type,Transform parent,Vector3 position,Vector3 scale,Material mat)
    {
        var g=GameObject.CreatePrimitive(type);g.name=name;g.transform.SetParent(parent,false);g.transform.localPosition=position;g.transform.localScale=scale;
        UnityEngine.Object.DestroyImmediate(g.GetComponent<Collider>());g.GetComponent<Renderer>().sharedMaterial=mat;return g.transform;
    }
    static void Rope(string name,Transform parent,Vector3 a,Vector3 b,float radius,Material mat)
    {
        var t=Shape(name,PrimitiveType.Cylinder,parent,(a+b)*.5f,new Vector3(radius*2,(b-a).magnitude*.5f,radius*2),mat);
        t.localRotation=Quaternion.FromToRotation(Vector3.up,b-a);
    }
    static Shader WornShader(Shader source)
    {
        string sourcePath=AssetDatabase.GetAssetPath(source),code=File.ReadAllText(sourcePath);
        const string varying="half fog:TEXCOORD3;",vertex="o.uv=TRANSFORM_TEX(v.uv,_BaseMap);",lighting="d.viewDirectionWS=GetWorldSpaceNormalizeViewDir(i.positionWS);";
        if(!code.Contains(varying)||!code.Contains(vertex)||!code.Contains(lighting))throw new Exception("Source shader changed: "+sourcePath);
        code=code.Replace("Shader \""+source.name+"\"","Shader \"CurtainCall/Endings/Survivor "+Path.GetFileNameWithoutExtension(sourcePath)+"\"");
        int property=code.IndexOf('{',code.IndexOf("Properties"));code=code.Insert(property+1,"\n        _EndingBlood(\"Ending dry stains\", Range(0,1))=.55\n");
        code=code.Replace("CBUFFER_END","half _EndingBlood;\n        CBUFFER_END");
        code=code.Replace(varying,varying+" float3 endingPositionOS:TEXCOORD4;");
        code=code.Replace(vertex,vertex+" o.endingPositionOS=v.positionOS.xyz;");
        code=code.Replace("half4 Frag(Varyings i):SV_Target","#include \"SuccessCostumeWear.hlsl\"\n        half4 Frag(Varyings i):SV_Target");
        code=code.Replace(lighting,"ApplySuccessCostumeWear(s,d,i.endingPositionOS,i.uv);\n            "+lighting);
        string destination=Shaders+"/Survivor"+Path.GetFileName(sourcePath);
        code="// Generated by SuccessArtBuilder. Source palette and pattern logic preserved.\n"+code.TrimEnd()+"\n";
        if(!File.Exists(destination)||File.ReadAllText(destination)!=code)File.WriteAllText(destination,code);
        AssetDatabase.ImportAsset(destination,ImportAssetOptions.ForceSynchronousImport);
        return AssetDatabase.LoadAssetAtPath<Shader>(destination);
    }
    public static object Build()
    {
        if(EditorApplication.isPlaying)throw new Exception("Stop play mode before building assets.");
        Directory.CreateDirectory(Art);Directory.CreateDirectory(Prefabs);AssetDatabase.Refresh();random=new System.Random(131);
        var ground=Mat("Damp weathered soil",new Color(.67f,.59f,.45f),0);
        ground.SetTexture("_BaseMap",AssetDatabase.LoadAssetAtPath<Texture2D>("Assets/_ThirdParty/LeartesStudios/HDRP/Art/Textures/T_Dirt_BC.png"));
        ground.SetTexture("_BumpMap",AssetDatabase.LoadAssetAtPath<Texture2D>("Assets/_ThirdParty/LeartesStudios/HDRP/Art/Textures/T_Dirt_N.png"));
        var grass=Mat("Dry reed leaves",new Color(.36f,.33f,.18f),2);grass.SetFloat("_Wind",.075f);
        var stem=Mat("Reed stems and seeds",new Color(.40f,.31f,.18f),2);stem.SetFloat("_Wind",.035f);
        var stones=Mat("Dark flint and clods",new Color(.26f,.24f,.20f),3);
        var red=Mat("Faded oxblood canvas",new Color(.33f,.12f,.10f),1);
        var cream=Mat("Weathered cream canvas",new Color(.63f,.54f,.39f),1);
        var rope=Mat("Frayed guy ropes",new Color(.30f,.26f,.18f),1);
        var iron=Mat("Rusty stakes and poles",new Color(.17f,.12f,.09f),3);
        var black=Mat("Unlit entrance",new Color(.009f,.011f,.012f),3);
        var tile=Node("Detailed meadow tile",null);
        ResetMesh();
        // Flat corridor preserves the actual running collider; subtle irregularity beside it.
        for(int x=0;x<130;x++)for(int z=0;z<120;z++)
        {
            Vector3 P(int a,int b){float px=a-65,pz=b-60;float h=Mathf.PerlinNoise((px+131)*.7f,(pz+131)*.7f)*.05f;return new Vector3(px,h-.025f,pz);}
            Quad(P(x,z),P(x+1,z),P(x+1,z+1),P(x,z+1));
        }
        MeshObject("Uneven soil",tile,SaveMesh("Soil mesh"),ground);
        ResetMesh();
        for(int clump=0;clump<2300;clump++)
        {
            float x=R(0,1)<.75f?R(-15,15):R(-64,64),z=R(-60,60);if(Mathf.Abs(x)<2.3f&&R(0,1)<.89f)continue;
            for(int blade=0;blade<7;blade++)
            {
                Vector3 root=new(x+R(-.28f,.28f),0,z+R(-.28f,.28f));float height=R(.22f,1.05f),yaw=R(0,Mathf.PI*2),width=R(.008f,.022f);
                Vector3 side=new(Mathf.Cos(yaw),0,Mathf.Sin(yaw)),bend=new(Mathf.Sin(yaw)*R(.1f,.4f),0,Mathf.Cos(yaw)*R(.1f,.4f));
                for(int seg=0;seg<4;seg++)
                {
                    float a=seg/4f,b=(seg+1)/4f;Vector3 low=root+Vector3.up*height*a+bend*a*a,high=root+Vector3.up*height*b+bend*b*b;
                    Quad(low-side*width*(1-a),low+side*width*(1-a),high+side*width*(1-b),high-side*width*(1-b),a,b);
                }
            }
        }
        MeshObject("Fine wind bent blades",tile,SaveMesh("Fine grass mesh"),grass);
        ResetMesh();
        for(int reed=0;reed<1600;reed++)
        {
            float x=R(0,1)<.7f?R(-18,18):R(-63,63),z=R(-60,60);if(Mathf.Abs(x)<3.2f)continue;
            var root=new Vector3(x,0,z);float h=R(.65f,1.8f);Vector3 top=root+new Vector3(R(-.18f,.18f),h,R(-.18f,.18f));
            for(int cross=0;cross<2;cross++)
            {
                Vector3 side=cross==0?Vector3.right:Vector3.forward;
                Quad(root-side*.012f,root+side*.012f,top+side*.007f,top-side*.007f);
                Vector3 tip=top+Vector3.up*R(.12f,.25f);
                Quad(top-side*.045f,top+side*.045f,tip+side*.006f,tip-side*.006f,.75f,1);
            }
        }
        MeshObject("Sparse seed heads",tile,SaveMesh("Reed heads mesh"),stem);
        ResetMesh();
        for(int j=0;j<1100;j++)
        {
            Vector3 p=new(R(0,1)<.8f?R(-9,9):R(-64,64),-.012f,R(-60,60));float size=R(.025f,.11f),stretch=R(.7f,1.7f);
            var top=p+new Vector3(size*.13f,size*.38f,-size*.08f);
            for(int k=0;k<8;k++)
            {
                float a=k*Mathf.PI/4,b=(k+1)*Mathf.PI/4;
                var l=new Vector3(Mathf.Cos(a)*size,0,Mathf.Sin(a)*size*stretch);var r=new Vector3(Mathf.Cos(b)*size,0,Mathf.Sin(b)*size*stretch);
                Quad(p+l,p+r,top+r*.48f,top+l*.48f);Quad(top+l*.48f,top+r*.48f,top,top);
            }
        }
        MeshObject("Loose flint clods",tile,SaveMesh("Pebble mesh"),stones);
        var tilePrefab=PrefabUtility.SaveAsPrefabAsset(tile.gameObject,Prefabs+"/SuccessMeadowTile.prefab");UnityEngine.Object.DestroyImmediate(tile.gameObject);
        var rootArt=Node("Success ending art",null);var circus=Node("Weathered distant circus",rootArt);circus.localPosition=new Vector3(0,-.1f,-73);
        for(int color=0;color<2;color++)
        {
            ResetMesh();
            for(int sector=color;sector<32;sector+=2)for(int ring=0;ring<8;ring++)for(int segment=0;segment<4;segment++)
            {
                Vector3 P(int r,int s){float f=r/8f,a=(sector+s/4f)*Mathf.PI/16,rad=24*f;float sag=Mathf.Sin(s*Mathf.PI/4)*Mathf.Sin(f*Mathf.PI)*1.5f;return new Vector3(Mathf.Sin(a)*rad,29-21*Mathf.Pow(f,.56f)-sag,Mathf.Cos(a)*rad);}
                Quad(P(ring,segment),P(ring,segment+1),P(ring+1,segment+1),P(ring+1,segment),ring/8f,(ring+1)/8f);
            }
            MeshObject(color==0?"Red sagging roof panels":"Cream sagging roof panels",circus,SaveMesh("Canvas roof "+color),color==0?red:cream);
            ResetMesh();
            for(int sector=color;sector<32;sector+=2)for(int segment=0;segment<4;segment++)
            {
                // A real dark opening, with split canvas sides facing the escaping players.
                if(sector==0||sector==31)continue;
                Vector3 P(int s,float y){float a=(sector+s/4f)*Mathf.PI/16,rad=24+Mathf.Sin(s*Mathf.PI/4)*.35f;return new Vector3(Mathf.Sin(a)*rad,y,Mathf.Cos(a)*rad);}
                Quad(P(segment,0),P(segment+1,0),P(segment+1,8),P(segment,8));
            }
            MeshObject(color==0?"Red wall folds":"Cream wall folds",circus,SaveMesh("Canvas wall "+color),color==0?red:cream);
        }
        Shape("Entrance shadow",PrimitiveType.Cube,circus,new Vector3(0,3.9f,20),new Vector3(10,7.8f,.3f),black);
        Rope("Center mast",circus,new Vector3(0,0,0),new Vector3(0,31,0),.14f,iron);
        for(int j=0;j<24;j++)
        {
            float a=j*Mathf.PI/12;var edge=new Vector3(Mathf.Sin(a)*24,8,Mathf.Cos(a)*24);var stake=new Vector3(Mathf.Sin(a)*33,.12f,Mathf.Cos(a)*33);
            for(int ring=0;ring<8;ring++)
            {
                Vector3 Seam(float f)=>new Vector3(Mathf.Sin(a)*24*f,29.08f-21*Mathf.Pow(f,.56f),Mathf.Cos(a)*24*f);
                Rope("Canvas seam",circus,Seam(ring/8f),Seam((ring+1)/8f),.025f,rope);
            }
            Rope("Tensioned guy rope",circus,edge,stake,.028f,rope);Rope("Rust stake",circus,stake-Vector3.up*.3f,stake+Vector3.up*.6f,.07f,iron);
        }
        ResetMesh();
        for(int j=0;j<12;j++)
        {
            float x=j*.62f;Quad(new Vector3(x,30,0),new Vector3(x+.45f,30,.1f),new Vector3(x+.3f,29.35f,.18f),new Vector3(x+.3f,29.35f,.18f));
        }
        MeshObject("Faded torn pennants",circus,SaveMesh("Pennants"),red);
        Rope("Pennant line",circus,new Vector3(0,30,0),new Vector3(7.5f,30,0),.015f,rope);
        var skyMat=AssetDatabase.LoadAssetAtPath<Material>(Art+"/Overcast sky.mat");
        if(skyMat==null){skyMat=new Material(Shader.Find("CurtainCall/Endings/Success Overcast Sky"));AssetDatabase.CreateAsset(skyMat,Art+"/Overcast sky.mat");}
        var sky=Shape("Overcast sky",PrimitiveType.Sphere,rootArt,Vector3.zero,Vector3.one*380,skyMat);
        sky.GetComponent<Renderer>().shadowCastingMode=UnityEngine.Rendering.ShadowCastingMode.Off;sky.GetComponent<Renderer>().receiveShadows=false;
        string[] names={"Rabbit/RabbitBloodPaper","Bear/BearPaper","BluePierrot/BluePierrotPaper","PinkGirl/PinkGirlPaper"};
        var component=rootArt.gameObject.AddComponent<EscapeEndingArt>();var serialized=new SerializedObject(component);
        serialized.FindProperty("fieldTile").objectReferenceValue=tilePrefab;serialized.FindProperty("sky").objectReferenceValue=sky;
        var sources=serialized.FindProperty("sourceShaders");var worn=serialized.FindProperty("wornShaders");sources.arraySize=worn.arraySize=names.Length;
        for(int i=0;i<names.Length;i++){var shader=AssetDatabase.LoadAssetAtPath<Shader>("Assets/_ThirdParty/CharacterArt/"+names[i]+".shader");sources.GetArrayElementAtIndex(i).objectReferenceValue=shader;worn.GetArrayElementAtIndex(i).objectReferenceValue=WornShader(shader);}
        serialized.ApplyModifiedPropertiesWithoutUndo();
        PrefabUtility.SaveAsPrefabAsset(rootArt.gameObject,Prefabs+"/SuccessEndingArt.prefab");UnityEngine.Object.DestroyImmediate(rootArt.gameObject);
        var settings=AssetDatabase.LoadAssetAtPath<CurtainCall.Settings.EscapeRouteSettings>("Assets/Resources/Settings/GameSettings/EscapeRouteSettings.asset");
        var config=new SerializedObject(settings);var day=config.FindProperty("endingDay");
        day.FindPropertyRelative("skyColor").colorValue=new Color(.42f,.46f,.50f);
        day.FindPropertyRelative("fogColor").colorValue=new Color(.035f,.045f,.055f);
        day.FindPropertyRelative("fogStartDistance").floatValue=18;day.FindPropertyRelative("fogEndDistance").floatValue=175;
        day.FindPropertyRelative("ambientColor").colorValue=new Color(.40f,.42f,.43f);
        day.FindPropertyRelative("lightColor").colorValue=new Color(.91f,.93f,1);day.FindPropertyRelative("lightIntensity").floatValue=1.35f;
        config.ApplyModifiedPropertiesWithoutUndo();EditorUtility.SetDirty(settings);AssetDatabase.SaveAssets();
        return new {prefab=Prefabs+"/SuccessEndingArt.prefab",terrain=tilePrefab.name,characters=names.Length};
    }
}
