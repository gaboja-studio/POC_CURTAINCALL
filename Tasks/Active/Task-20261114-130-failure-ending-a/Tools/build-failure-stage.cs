    static GameObject BuildMask(GameObject source,int index)
    {
        var instance=UnityEngine.Object.Instantiate(source);var output=new GameObject("CostumeMask"+index);
        try
        {
            var model=instance.GetComponentInChildren<HumanoidModel>();var skin=model.Original;
            model.GetComponent<RabbitSurfaceStates>()?.SetVariant(0);
            var head=model.Animator.GetBoneTransform(HumanBodyBones.Head);
            var baked=new Mesh();skin.BakeMesh(baked);
            var vertices=baked.vertices;var world=vertices.Select(v=>instance.transform.InverseTransformPoint(skin.transform.TransformPoint(v))).ToArray();
            float bottom=instance.transform.InverseTransformPoint(head.position).y;
            var triangles=new List<int[]>();var used=new HashSet<int>();
            for(int sub=0;sub<baked.subMeshCount;sub++)
            {
                var kept=new List<int>();var ids=baked.GetTriangles(sub);
                for(int i=0;i<ids.Length;i+=3)
                    if(world[ids[i]].y>bottom&&world[ids[i+1]].y>bottom&&world[ids[i+2]].y>bottom)
                    { for(int j=0;j<3;j++){kept.Add(ids[i+j]);used.Add(ids[i+j]);} }
                triangles.Add(kept.ToArray());
            }
            if(used.Count<30)throw new Exception("No mask surface: "+source.name);
            var bounds=new Bounds(world[used.First()],Vector3.zero);foreach(int v in used)bounds.Encapsulate(world[v]);
            float scale=.78f/bounds.size.y;
            // Preserve the original costume head volume; the back sits just in front of the wall.
            for(int i=0;i<vertices.Length;i++) {var v=(world[i]-bounds.center)*scale;vertices[i]=new Vector3(-v.x,v.y,-v.z);}
            baked.vertices=vertices;
            for(int i=0;i<triangles.Count;i++)baked.SetTriangles(triangles[i],i);
            baked.RecalculateNormals();baked.RecalculateBounds();baked.name="MaskSurface"+index;
            baked=Compact(baked);
            SmoothNormals(baked);
            string meshPath=Art+"/MaskSurface"+index+".asset";
            baked=SaveMesh(baked,meshPath);
            var surface=Node("FabricFace",output.transform);surface.gameObject.AddComponent<MeshFilter>().sharedMesh=baked;surface.gameObject.AddComponent<MeshRenderer>().sharedMaterials=CostumeMaterials(skin.sharedMaterials);
            surface.localPosition=new Vector3(0,0,-baked.bounds.max.z-.025f);
            foreach(int side in new[]{-1,1})
            {
                var target=new Vector3(baked.bounds.center.x+side*baked.bounds.size.x*.35f,baked.bounds.min.y+baked.bounds.size.y*.53f,baked.bounds.max.z);
                var attachment=Node(side<0?"RopeLeftAttachment":"RopeRightAttachment",surface);
                attachment.localPosition=baked.vertices.Where(v=>v.z>=baked.bounds.center.z).OrderBy(v=>(v-target).sqrMagnitude).First();
            }
            var saved=PrefabUtility.SaveAsPrefabAsset(output,Art+"/CostumeMask"+index+".prefab");return saved;
        }
        finally{UnityEngine.Object.DestroyImmediate(instance);UnityEngine.Object.DestroyImmediate(output);}
    }

    static GameObject BuildLimb(GameObject source,int modelIndex,int limbIndex)
    {
        var instance=UnityEngine.Object.Instantiate(source);
        var output=new GameObject("CostumeLimb"+modelIndex+"_"+limbIndex);
        try
        {
            var model=instance.GetComponentInChildren<HumanoidModel>();
            model.GetComponent<RabbitSurfaceStates>()?.SetVariant(0);
            var skin=model.Limbs[limbIndex];
            var lower=model.Animator.GetBoneTransform(new[]{HumanBodyBones.LeftLowerLeg,HumanBodyBones.RightLowerLeg,HumanBodyBones.LeftLowerArm,HumanBodyBones.RightLowerArm}[limbIndex]);
            lower.rotation=Quaternion.AngleAxis(new[]{18f,32f,42f,-58f}[limbIndex],limbIndex<2?instance.transform.right:instance.transform.forward)*lower.rotation;
            var mesh=new Mesh();skin.BakeMesh(mesh,false);
            var upper=model.Animator.GetBoneTransform(new[]{HumanBodyBones.LeftUpperLeg,HumanBodyBones.RightUpperLeg,HumanBodyBones.LeftUpperArm,HumanBodyBones.RightUpperArm}[limbIndex]);
            var end=model.Animator.GetBoneTransform(new[]{HumanBodyBones.LeftFoot,HumanBodyBones.RightFoot,HumanBodyBones.LeftHand,HumanBodyBones.RightHand}[limbIndex]);
            var turn=Quaternion.FromToRotation(instance.transform.InverseTransformDirection(end.position-upper.position).normalized,Vector3.forward);
            var vertices=mesh.vertices.Select(v=>turn*instance.transform.InverseTransformPoint(skin.transform.TransformPoint(v))).ToArray();
            var used=new HashSet<int>(mesh.triangles);
            var bounds=new Bounds(vertices[used.First()],Vector3.zero);foreach(int i in used)bounds.Encapsulate(vertices[i]);
            float scale=(limbIndex<2?1.2f:.95f)/bounds.size.z;
            var offset=new Vector3(bounds.center.x,bounds.min.y,bounds.center.z);
            for(int i=0;i<vertices.Length;i++)
            {
                var v=(vertices[i]-offset)*scale;
                float t=Mathf.InverseLerp(-bounds.size.z*scale*.5f,bounds.size.z*scale*.5f,v.z);
                if(limbIndex>=2)
                {
                    v.x*=1.5f;v.y*=1.4f;
                    // Let the lower sleeve settle to one side instead of a rigid T-pose rod.
                    float bend=Mathf.SmoothStep(0,limbIndex==2?28:-35,Mathf.InverseLerp(.38f,.66f,t));
                    v=Quaternion.Euler(0,bend,0)*v;
                }
                else v.y+=Mathf.Sin(t*Mathf.PI)*.10f;
                vertices[i]=v;
            }
            float bottom=used.Min(i=>vertices[i].y);
            for(int i=0;i<vertices.Length;i++)vertices[i].y-=bottom;
            mesh.vertices=vertices;mesh.RecalculateNormals();mesh.RecalculateBounds();mesh.name=output.name;
            mesh=Compact(mesh);
            SmoothNormals(mesh);
            string path=Art+"/"+output.name+".asset";
            mesh=SaveMesh(mesh,path);
            output.AddComponent<MeshFilter>().sharedMesh=mesh;
            var materials=CostumeMaterials(skin.sharedMaterials);
            // Preserve the costume texture, with neutral fabric over the existing closed end cap.
            for(int i=model.Original.sharedMesh.subMeshCount;i<materials.Length;i++)materials[i]=gold;
            output.AddComponent<MeshRenderer>().sharedMaterials=materials;
            return PrefabUtility.SaveAsPrefabAsset(output,Art+"/"+output.name+".prefab");
        }
        finally{UnityEngine.Object.DestroyImmediate(instance);UnityEngine.Object.DestroyImmediate(output);}
    }
