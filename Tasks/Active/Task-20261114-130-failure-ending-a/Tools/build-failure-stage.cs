    static Shader EndingCostumeShader(Shader source)
    {
        if(endingShaders.TryGetValue(source,out var existing))return existing;
        string path=AssetDatabase.GetAssetPath(source);
        string code=System.IO.File.ReadAllText(path);
        string name="CurtainCall/Endings/Aged "+source.name.Substring(source.name.LastIndexOf('/')+1);
        code=code.Replace("Shader \""+source.name+"\"","Shader \""+name+"\"");
        const string varying="half fog:TEXCOORD3;";
        const string vertex="o.uv=TRANSFORM_TEX(v.uv,_BaseMap);";
        const string lighting="d.viewDirectionWS=GetWorldSpaceNormalizeViewDir(i.positionWS);";
        if(!code.Contains(varying)||!code.Contains(vertex)||!code.Contains(lighting))throw new Exception("Review updated source costume shader: "+path);
        code=code.Replace(varying,varying+" float3 endingPositionOS:TEXCOORD4;");
        code=code.Replace(vertex,vertex+" o.endingPositionOS=v.positionOS.xyz;");
        code=code.Replace("half4 Frag(Varyings i):SV_Target","#include \"FailureCostumeWear.hlsl\"\n        half4 Frag(Varyings i):SV_Target");
        code=code.Replace(lighting,"ApplyFailureCostumeWear(s,d,i.endingPositionOS,i.uv);\n            "+lighting);
        code="// Generated by FailureStageBuilder from "+path+".\n// Source palette/pattern code is preserved; only the ending wear layer is appended.\n"+code.TrimEnd()+"\n";
        string destination=Art+"/Aged"+System.IO.Path.GetFileName(path);
        if(!System.IO.File.Exists(destination)||System.IO.File.ReadAllText(destination)!=code)
        {System.IO.File.WriteAllText(destination,code);AssetDatabase.ImportAsset(destination,ImportAssetOptions.ForceSynchronousImport);}
        var shader=AssetDatabase.LoadAssetAtPath<Shader>(destination);
        endingShaders[source]=shader;return shader;
    }
