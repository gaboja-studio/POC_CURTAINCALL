    static Mesh Compact(Mesh source)
    {
        var used=source.triangles.Distinct().OrderBy(i=>i).ToArray();
        var remap=new Dictionary<int,int>();for(int i=0;i<used.Length;i++)remap[used[i]]=i;
        var vertices=source.vertices;var uv=source.uv;var normals=source.normals;
        var mesh=new Mesh{name=source.name};
        mesh.vertices=used.Select(i=>vertices[i]).ToArray();
        mesh.uv=used.Select(i=>uv[i]).ToArray();mesh.normals=used.Select(i=>normals[i]).ToArray();
        mesh.subMeshCount=source.subMeshCount;
        for(int sub=0;sub<source.subMeshCount;sub++)mesh.SetTriangles(source.GetTriangles(sub).Select(i=>remap[i]).ToArray(),sub);
        mesh.RecalculateBounds();UnityEngine.Object.DestroyImmediate(source);return mesh;
    }
    static Mesh SaveMesh(Mesh mesh,string path)
    {
        var target=AssetDatabase.LoadAssetAtPath<Mesh>(path);
        if(target==null){AssetDatabase.CreateAsset(mesh,path);return mesh;}
        // CopySerialized leaves a previously rendered GPU mesh stale. Upload through the mesh API.
        target.Clear();target.indexFormat=mesh.indexFormat;target.name=mesh.name;
        target.SetVertices(mesh.vertices);target.SetNormals(mesh.normals);target.SetUVs(0,mesh.uv);
        if(mesh.tangents.Length==mesh.vertexCount)target.SetTangents(mesh.tangents);
        target.subMeshCount=mesh.subMeshCount;
        for(int sub=0;sub<mesh.subMeshCount;sub++)target.SetTriangles(mesh.GetTriangles(sub),sub);
        target.RecalculateBounds();EditorUtility.SetDirty(target);UnityEngine.Object.DestroyImmediate(mesh);return target;
    }
    static void SmoothNormals(Mesh mesh)
    {
        var vertices=mesh.vertices;var normals=mesh.normals;var output=new Vector3[normals.Length];
        var groups=new Dictionary<Vector3Int,List<int>>();
        for(int i=0;i<vertices.Length;i++)
        {
            var key=Vector3Int.RoundToInt(vertices[i]*10000);
            if(!groups.TryGetValue(key,out var ids))groups[key]=ids=new List<int>();ids.Add(i);
        }
        float crease=Mathf.Cos(68*Mathf.Deg2Rad);
        foreach(var ids in groups.Values)foreach(int i in ids)
        {
            var sum=Vector3.zero;
            foreach(int j in ids)if(Vector3.Dot(normals[i],normals[j])>=crease)sum+=normals[j];
            output[i]=sum.normalized;
        }
        mesh.normals=output;
    }
    static Mesh Tube(string name,Func<float,Vector3> center,float radius,int steps,int sides)
    {
        var vertices=new List<Vector3>();var uv=new List<Vector2>();var triangles=new List<int>();
        for(int i=0;i<=steps;i++)
        {
            float t=(float)i/steps;var p=center(t);var tangent=(center(Mathf.Min(1,t+.001f))-center(Mathf.Max(0,t-.001f))).normalized;
            var right=Vector3.Cross(tangent,Mathf.Abs(tangent.z)>.9f?Vector3.right:Vector3.forward).normalized;var up=Vector3.Cross(right,tangent).normalized;
            for(int j=0;j<=sides;j++)
            {
                float a=(float)j/sides*Mathf.PI*2;vertices.Add(p+radius*(right*Mathf.Cos(a)+up*Mathf.Sin(a)));uv.Add(new Vector2((float)j/sides,t*8));
                if(i<steps&&j<sides){int k=i*(sides+1)+j;triangles.AddRange(new[]{k,k+sides+1,k+1,k+1,k+sides+1,k+sides+2});}
            }
        }
        var mesh=new Mesh{name=name};mesh.SetVertices(vertices);mesh.SetUVs(0,uv);mesh.SetTriangles(triangles,0);mesh.RecalculateNormals();mesh.RecalculateBounds();return mesh;
    }
    static Mesh BulbEnvelope()
    {
        var profile=new[]{new Vector2(.035f,.10f),new Vector2(.037f,.045f),new Vector2(.065f,-.015f),new Vector2(.11f,-.085f),new Vector2(.13f,-.16f),new Vector2(.117f,-.235f),new Vector2(.065f,-.29f),new Vector2(0,-.312f)};
        var vertices=new List<Vector3>();var uv=new List<Vector2>();var triangles=new List<int>();const int sides=40,steps=56;
        for(int row=0;row<=steps;row++)
        {
            float u=(float)row/steps*(profile.Length-1);int j=Mathf.Min(Mathf.FloorToInt(u),profile.Length-2);float t=u-j;
            var a=profile[Mathf.Max(0,j-1)];var b=profile[j];var c=profile[j+1];var d=profile[Mathf.Min(profile.Length-1,j+2)];
            var p=.5f*((2*b)+(-a+c)*t+(2*a-5*b+4*c-d)*t*t+(-a+3*b-3*c+d)*t*t*t);
            for(int side=0;side<=sides;side++)
            {
                float angle=(float)side/sides*Mathf.PI*2;vertices.Add(new Vector3(Mathf.Max(0,p.x)*Mathf.Cos(angle),p.y,Mathf.Max(0,p.x)*Mathf.Sin(angle)));uv.Add(new Vector2((float)side/sides,(float)row/steps));
                if(row<steps&&side<sides){int k=row*(sides+1)+side;triangles.AddRange(new[]{k,k+1,k+sides+1,k+1,k+sides+2,k+sides+1});}
            }
        }
        var mesh=new Mesh{name="PearGlassEnvelope"};mesh.SetVertices(vertices);mesh.SetUVs(0,uv);mesh.SetTriangles(triangles,0);mesh.RecalculateNormals();SmoothNormals(mesh);return SaveMesh(mesh,Art+"/PearGlassEnvelope.asset");
    }
    static void Rope(string name,Transform parent,Vector3 start,Vector3 bend,Vector3 end,Material material,int variation)
    {
        string path=Art+"/"+name+variation+".asset";
        Vector3 Curve(float t)=>Vector3.Lerp(Vector3.Lerp(start,bend,t),Vector3.Lerp(bend,end,t),t);
        var pieces=new List<CombineInstance>();
        for(int strand=0;strand<3;strand++)
        {
            float offset=strand*Mathf.PI*2/3;
            Vector3 Strand(float t){var p=Curve(t);float a=t*38*Mathf.PI+offset;return p+new Vector3(Mathf.Cos(a)*.008f,0,Mathf.Sin(a)*.008f);}
            pieces.Add(new CombineInstance{mesh=Tube("HempStrand",Strand,.007f,90,6),transform=Matrix4x4.identity});
        }
        foreach(var center in new[]{start,end})
        {
            Vector3 Knot(float t){float a=t*Mathf.PI*4;return center+new Vector3(Mathf.Cos(a)*.025f,t*.035f-.0175f,Mathf.Sin(a)*.025f);}
            pieces.Add(new CombineInstance{mesh=Tube("Knot",Knot,.009f,36,6),transform=Matrix4x4.identity});
        }
        var mesh=new Mesh{name=name+variation};mesh.CombineMeshes(pieces.ToArray(),true,true);
        foreach(var piece in pieces)UnityEngine.Object.DestroyImmediate(piece.mesh);
        mesh=SaveMesh(mesh,path);
        var go=Node(name,parent);go.gameObject.AddComponent<MeshFilter>().sharedMesh=mesh;go.gameObject.AddComponent<MeshRenderer>().sharedMaterial=material;
    }
